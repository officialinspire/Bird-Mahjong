// Bird Mahjong service worker: offline play after the first successful load.
//
// Consistency first. Every file the game needs is precached into ONE cache
// named after VERSION, and every request is answered from that cache. A page
// is therefore always served by a single, complete generation of files; old
// HTML never meets new JavaScript.
//
// Safe updates. VERSION is a hash of the precached files' contents, written
// by `npm run build:sw` (tests fail if it's stale), so any change to any
// cached file produces a new service worker:
//   1. The page registers with updateViaCache: "none" and checks for an update
//      on every load and whenever it comes back to the foreground.
//   2. A new worker precaches the new version into a NEW cache (bypassing the
//      HTTP cache) while the old one keeps serving. If any file fails, the
//      install fails and nothing changes.
//   3. The new worker then waits. The page offers "Refresh"; tapping it
//      autosaves the board and tells the worker to take over (SKIP_WAITING),
//      and the page reloads once on controllerchange. If the player ignores
//      it, the new version starts on the next cold start (all tabs closed).
//   4. On activate, caches from older versions are deleted.
//
// Paths are relative to the worker's scope, so the same file works at a
// domain root and under /Bird-Mahjong/ on GitHub Pages.


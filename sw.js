const scoped = (path) => new URL(path, self.registration.scope).href;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      // cache: "reload" skips the HTTP cache so a new version never mixes in
      // stale files that GitHub Pages' CDN or the browser still hold.
      cache.addAll(PRECACHE.map((path) => new Request(scoped(path), { cache: "reload" })))
    )
  );
  // No skipWaiting here: an update waits until the player chooses to refresh
  // (or next cold start), so a running game is never swapped mid-session.
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE && key !== RUNTIME).map((key) => caches.delete(key))
      );
      // Runtime-cached extras (e.g. the tile gallery) may be from an older
      // version; start them fresh too.
      await caches.delete(RUNTIME);
      await self.clients.claim();
    })()
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
  if (event.data && event.data.type === "GET_VERSION") event.source?.postMessage({ type: "VERSION", version: VERSION });
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;

  // Game navigations (any query, e.g. ?seed=5) get the cached app shell.
  if (request.mode === "navigate" && isAppShell(url)) {
    event.respondWith(fromCache(scoped("./")).then((hit) => hit || fetch(request)));
    return;
  }

  event.respondWith(
    (async () => {
      const cached = await caches.match(request, { cacheName: CACHE, ignoreSearch: true });
      if (cached) return cached;
      // Not part of the game (e.g. tiles.html, full-size PNGs): network first,
      // keeping a copy so it also works offline after one visit.
      try {
        const response = await fetch(request);
        if (response.ok) (await caches.open(RUNTIME)).put(request, response.clone());
        return response;
      } catch (error) {
        const fallback = await caches.match(request, { cacheName: RUNTIME, ignoreSearch: true });
        if (fallback) return fallback;
        throw error;
      }
    })()
  );
});

function isAppShell(url) {
  const path = url.href.slice(self.registration.scope.length).split(/[?#]/)[0];
  return path === "" || path === "index.html";
}

async function fromCache(href) {
  return caches.match(href, { cacheName: CACHE });
}
